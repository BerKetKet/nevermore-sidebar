use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let plugins_dir = Path::new(&manifest_dir).join("src").join("plugins");
    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("plugins_gen.rs");

    println!("cargo:rerun-if-changed=src/plugins");
    println!("cargo:rerun-if-changed=resources/icons");

    let mut discovered = Vec::new();

    if plugins_dir.exists() {
        if let Ok(entries) = fs::read_dir(&plugins_dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if !path.is_dir() {
                    continue;
                }
                let dir_name = entry.file_name().to_string_lossy().to_string();
                if dir_name.starts_with('_') {
                    continue;
                }
                // Skip core legacy plugins
                if matches!(
                    dir_name.as_str(),
                    "terminal" | "widgets" | "notifications" | "notepad" | "placeholders"
                ) {
                    continue;
                }

                let mod_rs = path.join("mod.rs");
                if mod_rs.exists() {
                    if let Ok(content) = fs::read_to_string(&mod_rs) {
                        if content.contains("pub const SPEC: PluginSpec") {
                            discovered.push(dir_name);
                        }
                    }
                }
            }
        }
    }

    discovered.sort();

    let mut code = String::new();
    code.push_str("// Auto-generated by crates/nevermore-ui/build.rs — DO NOT EDIT\n\n");

    for id in &discovered {
        let mod_ident = format!("plugin_{}", id.replace('-', "_"));
        code.push_str(&format!(
            "#[path = \"{}/src/plugins/{}/mod.rs\"]\npub mod {};\n",
            manifest_dir, id, mod_ident
        ));
    }

    code.push_str("\npub static ALL_DISCOVERED_SPECS: &[crate::sdk::types::PluginSpec] = &[\n");
    for id in &discovered {
        let mod_ident = format!("plugin_{}", id.replace('-', "_"));
        code.push_str(&format!("    {}::SPEC,\n", mod_ident));
    }
    code.push_str("];\n\n");

    code.push_str("#[allow(clippy::type_complexity)]\n");
    code.push_str("pub static ALL_DISCOVERED_PLUGINS: &[(crate::sdk::types::PluginSpec, fn(&crate::plugin_api::PluginContext) -> gtk4::Widget)] = &[\n");
    for id in &discovered {
        let mod_ident = format!("plugin_{}", id.replace('-', "_"));
        code.push_str(&format!(
            "    ({}::SPEC, {}::build),\n",
            mod_ident, mod_ident
        ));
    }
    code.push_str("];\n\n");

    code.push_str("#[allow(dead_code, clippy::type_complexity, clippy::vec_init_then_push)]\n");
    code.push_str("pub fn register_discovered_spec_plugins(\n");
    code.push_str("    registry: &mut PluginRegistry,\n");
    code.push_str(
        "    theme: std::rc::Rc<std::cell::RefCell<nevermore_core::theme::ThemePalette>>,\n",
    );
    code.push_str("    tmux: nevermore_core::TmuxBackend,\n");
    code.push_str("    systemd: nevermore_core::SystemdTaskBackend,\n");
    code.push_str("    kwin: nevermore_core::KWinAdapter,\n");
    code.push_str("    blade: Option<std::rc::Rc<crate::companion_blade::CompanionBlade>>,\n");
    code.push_str(") {\n");
    code.push_str("    let mut plugins: Vec<(crate::sdk::types::PluginSpec, fn(&crate::plugin_api::PluginContext) -> gtk4::Widget)> = ALL_DISCOVERED_PLUGINS.to_vec();\n");
    code.push_str("    plugins.sort_by(|(a, _), (b, _)| a.order.cmp(&b.order).then_with(|| a.id.cmp(b.id)));\n");
    code.push_str("    for i in 0..plugins.len() {\n");
    code.push_str("        for j in (i + 1)..plugins.len() {\n");
    code.push_str("            if plugins[i].0.id == plugins[j].0.id {\n");
    code.push_str(
        "                panic!(\"Duplicate plugin ID detected: '{}'\", plugins[i].0.id);\n",
    );
    code.push_str("            }\n");
    code.push_str("        }\n");
    code.push_str("    }\n");
    code.push_str("    let disabled_ids: Vec<String> = {\n");
    code.push_str("        let cfg_path = nevermore_core::theme::config_file_path();\n");
    code.push_str("        if cfg_path.exists() {\n");
    code.push_str("            if let Ok(content) = std::fs::read_to_string(&cfg_path) {\n");
    code.push_str("                if let Ok(table) = toml::from_str::<toml::Table>(&content) {\n");
    code.push_str("                    table.get(\"plugins\")\n");
    code.push_str("                        .and_then(|p| p.get(\"disabled\"))\n");
    code.push_str("                        .and_then(|d| d.as_array())\n");
    code.push_str("                        .map(|arr| arr.iter().filter_map(|v| v.as_str().map(|s| s.to_string())).collect())\n");
    code.push_str("                        .unwrap_or_default()\n");
    code.push_str("                } else {\n");
    code.push_str("                    Vec::new()\n");
    code.push_str("                }\n");
    code.push_str("            } else {\n");
    code.push_str("                Vec::new()\n");
    code.push_str("            }\n");
    code.push_str("        } else {\n");
    code.push_str("            Vec::new()\n");
    code.push_str("        }\n");
    code.push_str("    };\n");
    code.push_str("    for (spec, build_fn) in plugins {\n");
    code.push_str("        if disabled_ids.iter().any(|d| d == spec.id) {\n");
    code.push_str("            eprintln!(\"[nevermore-plugin] Plugin '{}' is disabled in config.toml, skipping\", spec.id);\n");
    code.push_str("            continue;\n");
    code.push_str("        }\n");
    code.push_str("        let mut ctx = crate::plugin_api::PluginContext::new(\n");
    code.push_str("            spec.id,\n");
    code.push_str("            theme.clone(),\n");
    code.push_str("            tmux.clone(),\n");
    code.push_str("            systemd.clone(),\n");
    code.push_str("            kwin.clone(),\n");
    code.push_str("        );\n");
    code.push_str("        ctx.blade = blade.clone();\n");
    code.push_str("        let adapter = crate::sdk::lifecycle::SpecPluginAdapter::new(spec, build_fn, &ctx);\n");
    code.push_str("        registry.register(Box::new(adapter), &ctx);\n");
    code.push_str("    }\n");
    code.push_str("}\n");

    fs::write(&dest_path, code).unwrap();

    let icons_dir = Path::new(&manifest_dir).join("resources").join("icons");
    let icons_dest_path = Path::new(&out_dir).join("icons_gen.rs");
    let mut icons_code = String::new();
    icons_code.push_str("// Auto-generated by build.rs — DO NOT EDIT\n\n");
    icons_code.push_str("pub fn get_embedded_icon_svg(name: &str) -> Option<&'static str> {\n");
    icons_code.push_str("    match name {\n");

    if icons_dir.exists() {
        if let Ok(entries) = fs::read_dir(&icons_dir) {
            let mut entries: Vec<_> = entries.flatten().collect();
            entries.sort_by_key(|e| e.file_name());
            for entry in entries {
                let path = entry.path();
                if path.extension().and_then(|e| e.to_str()) == Some("svg") {
                    let stem = path.file_stem().unwrap().to_string_lossy().to_string();
                    icons_code.push_str(&format!(
                        "        \"{}\" | \"{}.svg\" => Some(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/resources/icons/{}.svg\"))),\n",
                        stem, stem, stem
                    ));
                }
            }
        }
    }

    icons_code.push_str("        _ => None,\n");
    icons_code.push_str("    }\n");
    icons_code.push_str("}\n");

    fs::write(&icons_dest_path, icons_code).unwrap();
}
